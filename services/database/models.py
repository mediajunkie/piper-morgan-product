class CrossDialectUUID(TypeDecorator):
    """UUID column type that works across PostgreSQL (native UUID) and SQLite (CHAR(36)).

    Issue #1038 (2026-05-16): unit tests for #1018 + sibling repositories run
    against in-memory SQLite, which can't bind Python `uuid.UUID` objects to a
    `String` column. SQLAlchemy 2.0+ provides `sqlalchemy.types.Uuid` which
    handles this transparently, but using that here would require checking
    whether the autogenerated Alembic migration is identical — risk-averse
    approach is to keep `postgresql.UUID(as_uuid=True)` as the canonical
    type and use this TypeDecorator only where SQLite test compatibility
    is needed (EthicsAuditLogDB.user_id at #1038 filing).

    On bind: converts `uuid.UUID` → str for non-Postgres dialects.
    On load: converts str → `uuid.UUID` for non-Postgres dialects.
    PostgreSQL path: no conversion (native UUID).
    """

    impl = CHAR
    cache_ok = True

    def load_dialect_impl(self, dialect):
        if dialect.name == "postgresql":
            return dialect.type_descriptor(postgresql.UUID(as_uuid=True))
        return dialect.type_descriptor(CHAR(36))

    def process_bind_param(self, value, dialect):
        if value is None or dialect.name == "postgresql":
            return value
        return str(value)

    def process_result_value(self, value, dialect):
        if value is None or dialect.name == "postgresql":
            return value
        if not isinstance(value, uuid.UUID):
            return uuid.UUID(value)
        return value


